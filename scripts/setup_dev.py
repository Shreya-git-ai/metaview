"""One-time local development setup.

    python scripts/setup_dev.py [--force]

1. Generates the local CA + TLS server certificate (certificates/).
2. Generates SYNTHETIC secrets (JWT secret, collector enrollment tokens, source-pseudonymisation salts)
   and writes them to config/*.env (git-ignored). No real credentials are ever used.
"""
from __future__ import annotations

import argparse
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.gen_certs import generate  # noqa: E402

COLLECTORS = [
    {"tenant": "tenant-alpha", "id": "col-alpha-01", "port": 9101,
     "hosts": "web-01.alpha.internal:web,app-01.alpha.internal:app,db-01.alpha.internal:db"},
    {"tenant": "tenant-beta", "id": "col-beta-01", "port": 9102,
     "hosts": "web-01.beta.internal:web,api-01.beta.internal:api"},
]


def main(force: bool) -> None:
    certs = generate(ROOT / "certificates", force=force)
    print("TLS material:", ", ".join(Path(p).name for p in certs.values()))

    cfg = ROOT / "config"
    cfg.mkdir(exist_ok=True)
    saas_env = cfg / "saas.env"
    if saas_env.exists() and not force:
        print("config/*.env already exist (use --force to regenerate secrets).")
        return

    tokens = {c["tenant"]: "enr_" + secrets.token_urlsafe(24) for c in COLLECTORS}
    saas_env.write_text("\n".join([
        "# SaaS backend — generated by scripts/setup_dev.py (synthetic dev secrets)",
        "SAAS_HOST=127.0.0.1",
        "SAAS_PORT=8443",
        "SAAS_DB_PATH=data/saas/saas.db",
        "SAAS_TLS_CERT=certificates/server.pem",
        "SAAS_TLS_KEY=certificates/server.key",
        f"SAAS_JWT_SECRET={secrets.token_urlsafe(32)}",
        "SAAS_ENROLLMENT_TOKENS=" + ",".join(f"{t}:{tok}" for t, tok in tokens.items()),
        "SAAS_DEMO_PASSWORD=Demo#2026",
        "SAAS_HEARTBEAT_TIMEOUT_S=30",
        "SAAS_STALE_AFTER_S=15",
        "SAAS_CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173",
        "",
    ]), encoding="utf-8")

    for c in COLLECTORS:
        (cfg / f"{c['id']}.env").write_text("\n".join([
            f"# Local collector {c['id']} — generated by scripts/setup_dev.py (synthetic dev secrets)",
            f"COLLECTOR_TENANT_ID={c['tenant']}",
            f"COLLECTOR_ID={c['id']}",
            "COLLECTOR_SAAS_URL=https://localhost:8443",
            "COLLECTOR_CA_CERT=certificates/ca.pem",
            f"COLLECTOR_ENROLLMENT_TOKEN={tokens[c['tenant']]}",
            f"COLLECTOR_DATA_DIR=data/{c['id']}",
            f"COLLECTOR_CONSOLE_PORT={c['port']}",
            f"COLLECTOR_HOSTS={c['hosts']}",
            f"COLLECTOR_SOURCE_SALT={secrets.token_hex(16)}",
            "COLLECTOR_SAMPLE_INTERVAL_S=1",
            "COLLECTOR_WINDOW_S=3",
            "COLLECTOR_HEARTBEAT_S=5",
            "",
        ]), encoding="utf-8")
    print("Wrote config/saas.env and", ", ".join(f"config/{c['id']}.env" for c in COLLECTORS))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    main(ap.parse_args().force)
